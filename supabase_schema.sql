-- ============================================================================
-- SKRIP SKEMA DATABASE SUPABASE (POSTGRESQL) UNTUK SISTEM SELEKSI KIP-KULIAH UNIHAZ
-- Jalankan skrip ini di: Supabase Dashboard -> SQL Editor -> New Query -> Run
-- ============================================================================

-- 1. TABEL TAHUN AKADEMIK (academic_years)
CREATE TABLE IF NOT EXISTS public.academic_years (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL,
    semester VARCHAR(20) NOT NULL DEFAULT 'Ganjil',
    quota INTEGER NOT NULL DEFAULT 120,
    start_date VARCHAR(20) NOT NULL,
    end_date VARCHAR(20) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT false,
    description TEXT,
    participants_count INTEGER DEFAULT 0,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. TABEL FAKULTAS (faculties)
CREATE TABLE IF NOT EXISTS public.faculties (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL UNIQUE,
    name VARCHAR(255) NOT NULL,
    dean VARCHAR(255) NOT NULL,
    building VARCHAR(255),
    is_active BOOLEAN NOT NULL DEFAULT true,
    study_programs_count INTEGER DEFAULT 0,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. TABEL PROGRAM STUDI (study_programs)
CREATE TABLE IF NOT EXISTS public.study_programs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL UNIQUE,
    name VARCHAR(255) NOT NULL,
    degree VARCHAR(20) NOT NULL DEFAULT 'S1',
    faculty_id BIGINT NOT NULL,
    faculty_name VARCHAR(255),
    quota INTEGER NOT NULL DEFAULT 15,
    accreditation VARCHAR(50) NOT NULL DEFAULT 'Baik Sekali',
    is_active BOOLEAN NOT NULL DEFAULT true,
    title VARCHAR(50) NOT NULL DEFAULT 'S.Kom.',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. TABEL PENGGUNA / OPERATOR RBAC (users)
CREATE TABLE IF NOT EXISTS public.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    username VARCHAR(100) NOT NULL UNIQUE,
    email VARCHAR(255) NOT NULL UNIQUE,
    role VARCHAR(100) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT true,
    last_login_at VARCHAR(50),
    avatar_url TEXT,
    password TEXT NOT NULL DEFAULT 'Operator@12345',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 5. TABEL BOBOT SELEKSI (selection_weights)
CREATE TABLE IF NOT EXISTS public.selection_weights (
    id BIGINT PRIMARY KEY DEFAULT 1,
    utbk_weight DOUBLE PRECISION NOT NULL DEFAULT 35,
    interview_weight DOUBLE PRECISION NOT NULL DEFAULT 25,
    survey_weight DOUBLE PRECISION NOT NULL DEFAULT 25,
    affirmation_weight DOUBLE PRECISION NOT NULL DEFAULT 15,
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 6. TABEL CALON PESERTA KIP-KULIAH (participants)
CREATE TABLE IF NOT EXISTS public.participants (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reg_number VARCHAR(100) NOT NULL UNIQUE,
    name VARCHAR(255) NOT NULL,
    nisn VARCHAR(20) NOT NULL,
    nik VARCHAR(20) NOT NULL,
    academic_year_id BIGINT NOT NULL,
    academic_year_code VARCHAR(50),
    first_choice_prodi_id BIGINT NOT NULL,
    first_choice_prodi_name VARCHAR(255) NOT NULL,
    second_choice_prodi_id BIGINT DEFAULT 0,
    second_choice_prodi_name VARCHAR(255) DEFAULT '',
    school_origin VARCHAR(255) NOT NULL,
    school_type VARCHAR(20) DEFAULT 'SMA',
    school_major VARCHAR(100) DEFAULT 'MIPA',
    graduation_year INTEGER NOT NULL DEFAULT 2026,
    phone VARCHAR(50) NOT NULL,
    email VARCHAR(255) NOT NULL,
    address TEXT NOT NULL,
    city VARCHAR(100) NOT NULL,
    province VARCHAR(100) NOT NULL DEFAULT 'Bengkulu',
    desil VARCHAR(50) NOT NULL DEFAULT 'Desil 3',
    parent_name VARCHAR(255) NOT NULL,
    parent_income DOUBLE PRECISION NOT NULL DEFAULT 1000000,
    parent_job VARCHAR(255) NOT NULL DEFAULT 'Petani/Buruh',
    family_dependents INTEGER NOT NULL DEFAULT 3,
    document_status VARCHAR(50) NOT NULL DEFAULT 'Belum Diverifikasi',
    
    -- Kolom Verifikasi Berkas
    document_receiver VARCHAR(255),
    document_received_date VARCHAR(50),
    document_checker VARCHAR(255),
    document_checked_date VARCHAR(50),
    document_notes TEXT,
    document_checklist JSONB DEFAULT '{}'::jsonb,
    
    -- Kolom Survey Lapangan
    survey_score DOUBLE PRECISION,
    surveyor_name VARCHAR(255),
    survey_date VARCHAR(50),
    survey_notes TEXT,
    house_condition VARCHAR(50) DEFAULT 'Sederhana',
    
    -- Kolom Nilai Akademik & Wawancara
    utbk_score DOUBLE PRECISION,
    utbk_operator VARCHAR(255),
    utbk_date VARCHAR(50),
    utbk_notes TEXT,
    interview_score DOUBLE PRECISION,
    interviewer_name VARCHAR(255),
    interview_date VARCHAR(50),
    interview_notes TEXT,
    
    -- Hasil Kelulusan & Skor Akhir
    affirmation_score DOUBLE PRECISION,
    final_score DOUBLE PRECISION,
    selection_status VARCHAR(50) NOT NULL DEFAULT 'Belum Diproses',
    rank INTEGER,
    notes TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 7. TABEL AUDIT LOG (audit_logs)
CREATE TABLE IF NOT EXISTS public.audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    participant_id BIGINT,
    participant_name VARCHAR(255),
    action VARCHAR(255) NOT NULL,
    module VARCHAR(100) NOT NULL,
    changed_by VARCHAR(255) NOT NULL,
    role VARCHAR(100),
    old_status VARCHAR(100),
    new_status VARCHAR(100),
    details TEXT,
    severity VARCHAR(50) DEFAULT 'info',
    ip_address VARCHAR(100) DEFAULT '127.0.0.1',
    timestamp VARCHAR(50) NOT NULL
);

-- ============================================================================
-- NONAKTIFKAN ROW LEVEL SECURITY (RLS) ATAU BERIKAN AKSES PENUH ROLE ANON
-- Agar koneksi API anon Supabase dapat membaca & menulis data tanpa diblokir
-- ============================================================================
ALTER TABLE public.academic_years DISABLE ROW LEVEL SECURITY;
ALTER TABLE public.faculties DISABLE ROW LEVEL SECURITY;
ALTER TABLE public.study_programs DISABLE ROW LEVEL SECURITY;
ALTER TABLE public.users DISABLE ROW LEVEL SECURITY;
ALTER TABLE public.selection_weights DISABLE ROW LEVEL SECURITY;
ALTER TABLE public.participants DISABLE ROW LEVEL SECURITY;
ALTER TABLE public.audit_logs DISABLE ROW LEVEL SECURITY;

